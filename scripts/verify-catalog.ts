assert.equal(catalogItems.filter(item=>item.kind==="zodiac").length,12);
assert.equal(catalogItems.filter(item=>item.kind==="materials").length,6);
assert.equal(new Set(catalogItems.map(item=>item.id)).size,18);
assert.equal(new Set(catalogItems.map(item=>JSON.stringify([item.pitches,item.beats]))).size,18);
const before=JSON.stringify(catalogItems);
for(const item of catalogItems){
  const project=createCatalogProject(item,true);
  assert.deepEqual(validateProject(project),[],item.id);
  const checked=validateImportedProject(project);assert.equal(checked.ok,true,checked.ok?item.id:checked.message);
  const originals=userNotes(project),reply=project.tracks.lead.events.filter(note=>note.origin!=="user");
  assert.equal(originals.at(-1)!.startTick+originals.at(-1)!.durationTick,3840,item.id);
  assert.equal(reply.at(-1)!.startTick+reply.at(-1)!.durationTick,7680,item.id);
  const imported=importProjectJson(exportProjectJson(project));assert.equal(imported.ok,true);
  if(imported.ok){assert.deepEqual(imported.project.tracks,project.tracks);assert.deepEqual(imported.project.mixer,project.mixer)}
  const parsed=inspectMidi(exportProjectMidi(project));
  assert.ok(Math.abs((parsed.bpm??0)-90)<.001);assert.deepEqual(parsed.timeSignature,[4,4]);
  assert.equal(parsed.tracks.length,3);assert.equal(parsed.tracks[0]!.notes.length,project.tracks.lead.events.length*2);
  assert.equal(parsed.tracks[1]!.notes.length,project.tracks.bass.events.length*2);
  assert.equal(parsed.tracks[2]!.notes.length,project.tracks.drums.events.length*2);
  assert.equal(createResponseRequest(project,"catalog-check","rules").notes.length,originals.length);
  const copy=createMaterialCopy(item);assert.notEqual(copy.id,project.id);assert.ok(copy.title.endsWith("我的版本"));
  assert.deepEqual(copy.tracks,project.tracks);
  let state=initialStudioState(copy);
  state=studioReducer(state,{type:"dragStart"});
  state=studioReducer(state,{type:"move",id:originals[0]!.id,pitch:72,xNorm:.21});
  state=studioReducer(state,{type:"dragCommit"});
  assert.deepEqual(state.project.tracks.lead.events.filter(note=>note.origin!=="user"),reply,"moving a seed must preserve the preset response");
  assert.equal(validateImportedProject(state.project).ok,true,"edited material must remain importable");
  state=studioReducer(state,{type:"undo"});assert.deepEqual(state.project,copy);
}
