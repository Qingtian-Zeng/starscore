import assert from "node:assert/strict";
import { createResponseRequest, exportProjectJson, importProjectJson, userNotes, validateImportedProject, validateProject } from "@starscore/core";
import { catalogItems, createCatalogProject, createMaterialCopy, selectCatalogItems } from "../apps/web/src/catalog/catalog";
import { readFavoriteIds, writeFavoriteIds } from "../apps/web/src/catalog/favorites";
import { initialStudioState, studioReducer } from "../apps/web/src/studio/studioReducer";
import { exportProjectMidi, inspectMidi } from "../apps/web/src/files/midi";
